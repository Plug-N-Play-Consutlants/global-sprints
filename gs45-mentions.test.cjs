'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('src/gs45-mentions.js','utf8');
const context={Map,Set,Error};vm.createContext(context);vm.runInContext(source,context);
const mentions=vm.runInContext('GS45Mentions',context);
const A={id:'81fa6389-0872-6fdd-a451-7ba7880f566a',name:'Wendy Potter'};
const B={id:'c1ee1c64-2d1b-48c8-ad33-7f9d1afdd4cd',name:'Scott Developer'};
const selected=new Map();
let input='Thanks @Wen',match=mentions.active(input,input.length,selected);
assert.equal(match.name,'Wen');
let result=mentions.select(input,match,A);selected.set(result.token,A);
assert.equal(result.value,'Thanks @Wendy Potter ');assert.equal(result.caret,result.value.length);
assert.equal(mentions.active(result.value,result.caret,selected),null);
input=result.value+'please review this tomorrow';
assert.equal(mentions.active(input,input.length,selected),null,'typing after resolved mention must not initiate another identity search');
assert.deepEqual(Array.from(mentions.selectedTokens(input,selected)),['@Wendy Potter']);
console.log('PASS: selection remains resolved while typing ordinary words');
input+=' and @Sc';match=mentions.active(input,input.length,selected);
assert.equal(match.name,'Sc');result=mentions.select(input,match,B);selected.set(result.token,B);
input=result.value+'about <release> & testing';
assert.equal(mentions.active(input,input.length,selected),null);
const markup=mentions.serialize(input,selected);
assert.equal(markup.unresolved.length,0);
assert.equal((markup.html.match(/data-vss-mention=/g)||[]).length,2);
assert(markup.html.includes('&lt;release&gt; &amp; testing'));
console.log('PASS: two selected mentions stay linked and produce safe ADO markup');
input+=' and @Morgan';
const failed=mentions.serialize(input,selected);
assert.deepEqual(Array.from(failed.unresolved),['@Morgan'],'unresolved second mention must not be silently posted');
console.log('PASS: an unselected second mention is detected before writing');
input='Hi @Wendy Potter again';
mentions.prune(input,selected);
assert.equal(selected.size,1,'removed mention must be pruned');
assert.equal(mentions.active(input,input.length,selected),null);
input='Hi Wendy Potter again';mentions.prune(input,selected);
assert.equal(selected.size,0,'editing away @ removes the linked identity');
console.log('PASS: removing a mention removes its linked identity');
const unresolved=mentions.serialize('Address someone@example.com, not @Unknown',new Map());
assert.deepEqual(Array.from(unresolved.unresolved),['@Unknown']);
assert(!unresolved.html.includes('data-vss-mention'));
console.log('PASS: email addresses are not mistaken for mentions');
// Test the deployed handler uses a frozen candidate snapshot and invalidates an outstanding request.
const app=fs.readFileSync('src/app-main.js','utf8');
assert.match(app,/\+\+mentionQuerySeq;clearTimeout\(mentionSearchTimer\);clearMentionResults\(\)/);
assert.match(app,/candidate\.name!==match\.name/);
assert.match(app,/const applied=GS45Mentions\.select\(comment\.value,candidate,identity\)/);
assert.match(app,/choice\.addEventListener\('pointerdown',event=>event\.preventDefault\(\)\)/);
assert.match(app,/renderSelectedMentions\(\)/);
console.log('PASS: UI selection invalidates stale suggestions and visibly confirms linked people');
